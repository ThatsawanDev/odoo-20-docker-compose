# -*- coding: utf-8 -*-
# models/mcp_email_template.py

from odoo import api, fields, models
import logging

_logger = logging.getLogger(__name__)


class McpEmailTemplate(models.Model):
    """
    Thin wrapper around mail.template.
    LLM generates the HTML body — this model just stores it
    and auto-syncs to mail.template for sending.
    """
    _name        = 'mcp.email.template'
    _description = 'MCP Email Template'
    _order       = 'name asc'

    # ── core fields ───────────────────────────────────────────────────────────

    name = fields.Char(
        string='Template Name',
        required=True,
    )

    subject = fields.Char(
        string='Subject',
        required=True,
        help='Supports {{ object.name }} QWeb expressions',
    )

    body_html = fields.Text(
        string='Body HTML',
        required=True,
        help='Full HTML generated by LLM. Supports {{ object.field }} QWeb.',
    )

    # ── optional model binding ────────────────────────────────────────────────

    model_id = fields.Many2one(
        comodel_name='ir.model',
        string='Applies To',
        domain=[('transient', '=', False)],
        ondelete='set null',
        help='Set this to use {{ object.field }} expressions in body/subject.',
    )

    model = fields.Char(
        related='model_id.model',
        store=True,
        readonly=True,
    )

    # ── email headers ─────────────────────────────────────────────────────────

    email_from = fields.Char(
        string='From',
        default='{{ user.email_formatted }}',
    )

    email_to = fields.Char(
        string='To',
        help='Static address or {{ object.email }} / {{ object.partner_id.email }}',
    )

    # ── linked mail.template (created on generate) ────────────────────────────

    mail_template_id = fields.Many2one(
        comodel_name='mail.template',
        string='Mail Template',
        readonly=True,
        ondelete='set null',
        help='Auto-created when action_generate_template() is called.',
    )

    # ── state ─────────────────────────────────────────────────────────────────

    state = fields.Selection([
        ('draft',    'Draft'),
        ('ready',    'Ready'),
        ('tested',   'Tested'),
        ('archived', 'Archived'),
    ], default='draft', required=True)

    active = fields.Boolean(default=True)

    # ── mass mailing (optional — only if mass_mailing is installed) ───────────

    mass_mailing_id = fields.Many2one(
        comodel_name='mailing.mailing',
        string='Mass Mailing',
        readonly=True,
        ondelete='set null',
    )

    # ─────────────────────────────────────────────────────────────────────────
    # CORE METHOD — create / sync mail.template
    # ─────────────────────────────────────────────────────────────────────────

    def action_generate_template(self):
        """
        Create or update the linked mail.template.
        Called by the MCP tool on create (when model_id is set)
        and on every update.
        """
        self.ensure_one()

        if not self.model_id:
            raise ValueError(
                "Set 'Applies To' (model_id) before generating. "
                "Example: res.partner"
            )

        vals = {
            'name':        self.name,
            'model_id':    self.model_id.id,
            'subject':     self.subject,
            'body_html':   self.body_html,
            'email_from':  self.email_from or '{{ user.email_formatted }}',
            'email_to':    self.email_to or '',
            'auto_delete': True,
        }
        if self.mail_template_id:
            self.mail_template_id.write(vals)
        else:
            mt = self.env['mail.template'].create(vals)
            self.write({
                'mail_template_id': mt.id,
                'state':            'ready',
            })

        return {
            'type':  'ir.actions.client',
            'tag':   'display_notification',
            'params': {
                'title':   'Template Synced',
                'message': f"'{self.name}' is ready in Odoo Email Templates.",
                'type':    'success',
                'sticky':  False,
                'next':    {'type': 'ir.actions.act_window_close'},
            },
        }

    def action_open_mail_template(self):
        """Open the linked mail.template record in Odoo's Email Templates form."""
        self.ensure_one()
        if not self.mail_template_id:
            raise ValueError(
                "No linked Odoo email template found. "
                "Click 'Generate Template' first."
            )
        return {
            'type':      'ir.actions.act_window',
            'name':      'Odoo Email Template',
            'res_model': 'mail.template',
            'res_id':    self.mail_template_id.id,
            'view_mode': 'form',
            'target':    'current',
        }

    def action_create_mass_mailing(self):
        """
        Bridge: copy this template's body into a new mailing.mailing campaign
        and redirect the user to it so they can choose recipients and send.
        """
        self.ensure_one()

        # Guard: mass_mailing must be installed
        if 'mailing.mailing' not in self.env:
            raise ValueError(
                "The 'Email Marketing' (mass_mailing) module is not installed. "
                "Install it from Apps to use this feature."
            )

        if not self.body_html:
            raise ValueError(
                "This template has no body HTML. "
                "Generate or update the template first."
            )

        # Resolve recipient model for mailing.mailing
        # mailing.mailing.mailing_model_id must point to a model that has is_mailing_enabled
        mailing_model_id = False
        if self.model_id:
            # Check if target model is mailing-enabled
            ir_model = self.env['ir.model'].sudo().search(
                [('model', '=', self.model), ('is_mailing_enabled', '=', True)],
                limit=1
            )
            if ir_model:
                mailing_model_id = ir_model.id
            else:
                # Fall back to mailing.contact (always mailing-enabled)
                _logger.warning(
                    "Model '%s' is not mailing-enabled; "
                    "defaulting mass mailing to mailing.list recipients.",
                    self.model
                )

        # Default to mailing.list if no supported model
        if not mailing_model_id:
            mailing_model_id = self.env['ir.model'].sudo().search(
                [('model', '=', 'mailing.list')], limit=1
            ).id

        mailing_vals = {
            'subject':          self.subject,
            'email_from':       self.email_from or self.env.user.email_formatted,
            # body_arch = editable design; body_html = what gets sent
            'body_arch':        self.body_html,
            'body_html':        self.body_html,
            'mailing_model_id': mailing_model_id,
            'state':            'draft',
        }

        mailing = self.env['mailing.mailing'].sudo().create(mailing_vals)
        self.write({'mass_mailing_id': mailing.id})

        return {
            'type':      'ir.actions.act_window',
            'name':      'Mass Mailing',
            'res_model': 'mailing.mailing',
            'res_id':    mailing.id,
            'view_mode': 'form',
            'target':    'current',
        }

    def action_open_mass_mailing(self):
        """Redirect to the linked mailing.mailing campaign."""
        self.ensure_one()
        if not self.mass_mailing_id:
            raise ValueError(
                "No mass mailing linked yet. "
                "Click '📢 Create Mass Mailing' first."
            )
        return {
            'type':      'ir.actions.act_window',
            'name':      'Mass Mailing',
            'res_model': 'mailing.mailing',
            'res_id':    self.mass_mailing_id.id,
            'view_mode': 'form',
            'target':    'current',
        }


    # ─────────────────────────────────────────────────────────────────────────
    # ORM OVERRIDES
    # ─────────────────────────────────────────────────────────────────────────

    def write(self, vals):
        result = super().write(vals)
        # Keep mail.template in sync whenever body or subject changes
        if any(f in vals for f in ('body_html', 'subject', 'email_from', 'email_to')):
            for rec in self:
                if rec.mail_template_id:
                    sync = {}
                    if 'body_html'  in vals: sync['body_html']  = rec.body_html
                    if 'subject'    in vals: sync['subject']    = rec.subject
                    if 'email_from' in vals: sync['email_from'] = rec.email_from
                    if 'email_to'   in vals: sync['email_to']   = rec.email_to
                    rec.mail_template_id.write(sync)
        return result

    def unlink(self):
        # Delete linked mail.template when mcp record is deleted
        templates = self.mapped('mail_template_id')
        result    = super().unlink()
        templates.unlink()
        return result