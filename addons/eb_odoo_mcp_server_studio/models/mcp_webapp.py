class McpWebApp(models.Model):
    """
    React web applications generated by AI and stored inside Odoo.

    Tabs:
      Pages · API Endpoints · App Data & State · Styles · Dependencies ·
      Assets · User Storage · Sharing · Documentation
    """
    _name        = 'mcp.webapp'
    _description = 'MCP Web Application'
    _order       = 'write_date desc'
    _inherit     = ['mail.thread']

    # ── Core ─────────────────────────────────────────────────────────────────
    name        = fields.Char(string='App Name', required=True, tracking=True)
    slug        = fields.Char(string='URL Slug', required=True, index=True, copy=False)
    description = fields.Text(string='Description')

    # React source — the complete JSX component
    jsx_code    = fields.Text(string='React JSX Code')

    # Python data handler — runs server-side in safe_eval, returns JSON
    data_code   = fields.Text(string='Data Handler (Python)')

    # ── Configuration ────────────────────────────────────────────────────────
    mcp_client       = fields.Char(string='MCP Client', readonly=True,
                                    help='AI client that last generated this app.')
    # ── Tab: React JSX Code (existing) ───────────────────────────────────────
    jsx_code    = fields.Text(string='React JSX Code')

    # ── Tab: App Data & State (Python data handler) ───────────────────────────
    data_code   = fields.Text(string='Data Handler (Python)')
    app_state   = fields.Text(string='Initial App State (JSON)',
                               help='Optional JSON object injected into window.odoo.state at load time.')

    # ── Tab: Pages ────────────────────────────────────────────────────────────
    page_ids    = fields.One2many('mcp.webapp.page', 'webapp_id', string='Pages')

    # ── Tab: API Endpoints ────────────────────────────────────────────────────
    endpoint_ids = fields.One2many('mcp.webapp.endpoint', 'webapp_id', string='API Endpoints')

    # ── Tab: Styles ───────────────────────────────────────────────────────────
    custom_css  = fields.Text(string='Custom CSS',
                               help='Extra CSS injected into <style> in the app shell.')

    # ── Tab: Dependencies ─────────────────────────────────────────────────────
    dependencies = fields.Text(string='NPM / CDN Dependencies (JSON)',
                                help='JSON array of CDN script URLs or {name, url} objects to load before the app.')
    npm_packages = fields.Text(string='NPM Packages',
                                help='Comma-separated list of npm package names (for documentation purposes).')

    # ── Tab: Assets ───────────────────────────────────────────────────────────
    asset_ids   = fields.One2many('mcp.webapp.asset', 'webapp_id', string='Assets')

    # ── Tab: User Storage ─────────────────────────────────────────────────────
    user_storage_code = fields.Text(string='User Storage Handler (Python)',
                                     help='Server-side handler for persisting per-user data (read/write).')
    storage_schema    = fields.Text(string='Storage Schema (JSON)',
                                     help='JSON schema describing user storage keys and types.')

    # ── Tab: Sharing ──────────────────────────────────────────────────────────
    is_public   = fields.Boolean(string='Public Access', default=False, tracking=True,
                                  help='If True, accessible without login via the signed share URL.')
    sharing_mode = fields.Selection(
        [('private', 'Private — owner only'),
         ('token',   'Public — anyone with the share link'),
         ('group',   'Group — specific Odoo groups')],
        string='Sharing Mode', default='private')
    allowed_group_ids = fields.Many2many('res.groups', string='Allowed Groups',
                                          help='Groups whose members can access this app (when Sharing Mode = Group).')
    share_token = fields.Char(string='Share Token', readonly=True, copy=False, index=True)
    active      = fields.Boolean(default=True)

    # ── Tab: Documentation ────────────────────────────────────────────────────
    documentation = fields.Html(string='Documentation',
                                  help='Rich-text documentation for this app — architecture notes, usage guide, changelog.')

    # ── Runtime ───────────────────────────────────────────────────────────────
    user_id   = fields.Many2one('res.users', string='Created By',
                                 default=lambda self: self.env.user)
    app_url   = fields.Char(string='App URL', compute='_compute_app_url')
    share_url = fields.Char(string='Public Share URL', compute='_compute_app_url')

    @api.depends('slug', 'share_token', 'is_public')
    def _compute_app_url(self):
        base = self.env['ir.config_parameter'].sudo().get_str('web.base.url', '')
        for rec in self:
            rec.app_url = f"{base}/mcp/app/{rec.slug}" if rec.slug else ''
            if rec.is_public and rec.share_token:
                rec.share_url = f"{base}/mcp/app/public/{rec.id}/{rec.share_token}"
            else:
                rec.share_url = ''

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if not vals.get('slug'):
                vals['slug'] = secrets.token_urlsafe(8).lower().replace('-', '').replace('_', '')[:12]
            if not vals.get('share_token'):
                vals['share_token'] = secrets.token_urlsafe(32)
        return super().create(vals_list)

    def action_regenerate_token(self):
        for rec in self:
            rec.share_token = secrets.token_urlsafe(32)

    def action_open_app(self):
        self.ensure_one()
        return {
            'type':   'ir.actions.act_url',
            'url':    self.app_url,
            'target': 'new',
        }

