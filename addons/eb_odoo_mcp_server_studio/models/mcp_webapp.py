# -*- coding: utf-8 -*-
import secrets
from odoo import models, fields, api


class McpWebAppPage(models.Model):
    """A named page / route inside an MCP web application."""
    _name        = 'mcp.webapp.page'
    _description = 'MCP Web App Page'
    _order       = 'sequence, id'

    webapp_id    = fields.Many2one('mcp.webapp', string='App', ondelete='cascade', required=True)
    sequence     = fields.Integer(default=10)
    name         = fields.Char(string='Page Name', required=True)
    route_path   = fields.Char(string='Route Path', help='e.g. /orders, /orders/:id')
    page_title   = fields.Char(string='Page Title')
    jsx_code     = fields.Text(string='Page JSX Code',
                               help='React JSX component rendered at this route. '
                                    'Export nothing — define a default function Component() { … }.')

    def action_open_form_view(self):
        self.ensure_one()
        view_id = self.env.ref('eb_odoo_mcp_server_studio.view_mcp_webapp_page_form').id
        return {
            'type': 'ir.actions.act_window',
            'name': 'Page',
            'res_model': 'mcp.webapp.page',
            'res_id': self.id,
            'view_mode': 'form',
            'views': [(view_id, 'form')],
            'target': 'new',
        }


