# -*- coding: utf-8 -*-
import re
import secrets
from odoo import models, fields, api


class McpEChart(models.Model):
    """
    Apache ECharts dashboards generated by AI.
    Each chart has:
      - An ECharts option object (JSON)
      - A Python data handler that fetches live Odoo data
      - Optional pre/post init JavaScript hooks
      - Public shareable URL with token-based access
      - Embeddable via iframe

    Charts are served at:
      /mcp/echart/<slug>                          (internal)
      /mcp/echart/public/<id>/<token>             (public share)
      /mcp/echart/public/<id>/<token>?embed=1     (iframe embed)
    """
    _name        = 'mcp.echart'
    _description = 'MCP EChart Dashboard'
    _order       = 'write_date desc'
    _inherit     = ['mail.thread']

    _slug_unique = models.Constraint('UNIQUE(slug)', 'Chart URL slug must be unique.')

    # ── Core fields ────────────────────────────────────────────────────────
    name        = fields.Char(string='Chart Name', required=True, tracking=True)
    slug        = fields.Char(string='URL Slug', required=True, index=True, copy=False)
    description = fields.Text(string='Description')
    chart_type  = fields.Selection([
        ('bar',     'Bar Chart'),
        ('line',    'Line Chart'),
        ('pie',     'Pie / Donut Chart'),
        ('scatter', 'Scatter Plot'),
        ('heatmap', 'Heatmap'),
        ('radar',   'Radar Chart'),
        ('funnel',  'Funnel Chart'),
        ('gauge',   'Gauge'),
        ('map',     'Map / Globe'),
        ('treemap', 'Treemap'),
        ('sunburst', 'Sunburst'),
        ('sankey',  'Sankey'),
        ('custom',  'Custom'),
    ], string='Chart Type', default='bar')

    # ── Code fields ────────────────────────────────────────────────────────
    echart_option = fields.Text(
        string='ECharts Option (JSON)',
        help='Static JSON configuration for the ECharts instance. '
             'Arrays should be empty [] — data_code fills them at runtime.')
    data_code = fields.Text(
        string='Data Handler (Python)',
        help='Python code executed in safe_eval sandbox with full ORM access. '
             'Must set result = {dict}. Keys are deep-merged into echart_option.')
    pre_init_js = fields.Text(
        string='Pre-Init JavaScript',
        help='JavaScript executed BEFORE chart.setOption(). '
             'Use for: echarts.registerMap(), echarts.registerTheme(), '
             'loading external GeoJSON, etc. '
             'Available variables: echarts, chartDom, chart.')
    post_init_js = fields.Text(
        string='Post-Init JavaScript',
        help='JavaScript executed AFTER chart.setOption() and data load. '
             'Use for: chart.on("click", ...), drill-down handlers, '
             'export buttons, custom tooltips, etc. '
             'Available variables: echarts, chartDom, chart, option.')

    # ── Visibility & sharing ───────────────────────────────────────────────
    is_public   = fields.Boolean(string='Public Access', default=True,
                                  help='If True, the public share URL works without login.')
    active      = fields.Boolean(default=True)
    user_id     = fields.Many2one('res.users', string='Created By',
                                   default=lambda self: self.env.user)
    share_token = fields.Char(string='Share Token', readonly=True, copy=False, index=True,
                               help='Random token for the public share URL.')

    # ── Computed URL fields ────────────────────────────────────────────────
    chart_url   = fields.Char(string='Chart URL', compute='_compute_urls')
    share_url   = fields.Char(string='Public Share URL', compute='_compute_urls')
    embed_code  = fields.Text(string='Embed Code', compute='_compute_urls')

    @api.depends('slug', 'share_token', 'is_public')
    def _compute_urls(self):
        base = self.env['ir.config_parameter'].sudo().get_str('web.base.url', '')
        for rec in self:
            rec.chart_url = f"{base}/mcp/echart/{rec.slug}" if rec.slug else ''
            if rec.share_token and rec.is_public:
                pub = f"{base}/mcp/echart/public/{rec.id}/{rec.share_token}"
                rec.share_url = pub
                rec.embed_code = (
                    f'<iframe src="{pub}?embed=1" '
                    f'width="100%" height="700" '
                    f'style="border: none;" loading="lazy"></iframe>'
                )
            else:
                rec.share_url = ''
                rec.embed_code = ''

    @api.model
    def _generate_random_slug(self):
        return secrets.token_urlsafe(8).lower().replace('-', '').replace('_', '')[:12]

    @api.model
    def _slugify_value(self, value):
        slug = re.sub(r'[^a-z0-9]+', '-', (value or '').strip().lower()).strip('-')
        return slug[:48]

    @api.model
    def _make_unique_slug(self, base_slug, exclude_id=None):
        slug = base_slug or self._generate_random_slug()
        domain = [('slug', '=', slug)]
        if exclude_id:
            domain.append(('id', '!=', exclude_id))
        if not self.sudo().search_count(domain):
            return slug

        base = slug[:40].rstrip('-') or 'chart'
        max_attempts = 1000
        for suffix in range(2, 2 + max_attempts):
            candidate = f"{base}-{suffix}"
            domain = [('slug', '=', candidate)]
            if exclude_id:
                domain.append(('id', '!=', exclude_id))
            if not self.sudo().search_count(domain):
                return candidate
        # Fallback: use a random slug if all suffixes are taken
        return self._generate_random_slug()

    # ── Auto-generate slug & share_token on create ─────────────────────────
    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            slug_seed = self._slugify_value(vals.get('slug') or '')
            if vals.get('slug'):
                vals['slug'] = self._make_unique_slug(slug_seed or 'chart')
            else:
                vals['slug'] = self._make_unique_slug(self._generate_random_slug())
            if not vals.get('share_token'):
                vals['share_token'] = secrets.token_urlsafe(32)
        return super().create(vals_list)

    def write(self, vals):
        if 'slug' not in vals:
            return super().write(vals)

        for rec in self:
            rec_vals = dict(vals)
            slug_seed = self._slugify_value(rec_vals.get('slug') or '')
            rec_vals['slug'] = self._make_unique_slug(slug_seed or 'chart', exclude_id=rec.id)
            super(McpEChart, rec).write(rec_vals)
        return True

    # ── Actions ────────────────────────────────────────────────────────────
    def action_open_chart(self):
        self.ensure_one()
        return {
            'type':   'ir.actions.act_url',
            'url':    self.chart_url,
            'target': 'new',
        }

    def action_regenerate_token(self):
        """Regenerate the share token (invalidates old public URLs)."""
        for rec in self:
            rec.share_token = secrets.token_urlsafe(32)
